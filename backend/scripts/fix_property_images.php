/*
 |=============================================================================
 | Wajhatak — Fix Property Images (standalone maintenance script)
 |=============================================================================
 | Makes every property's images exist on the server disk at the exact
 | relative path stored in `property_images.path`, and binds each property to
 | its local files. A property never ends up with a broken 404 image URL.
 |
 | Why this exists:
 |   - Railway (and most PaaS) use an ephemeral disk: files written by the
 |     seeder are wiped on every redeploy/restart, so stored URLs return 404
 |     even though the database rows are intact (reprovisioning is skipped).
 |   - Some networks in Yemen cannot reach some public CDNs (Unsplash, etc.),
 |     so HTTP fetching alone is not a reliable fix. This script therefore
 |     uses a chain of sources and ALWAYS ends with a fully offline image
 |     generated by GD — the final result never depends on the network.
 |
 | Result: every `property_images.path` points to a real JPEG under
 | storage/app/public (served at {APP_URL}/storage/{path}), and images whose
 | paths were absolute external URLs are rebound to local files.
 |
 | Run it (from backend/):
 |   php scripts/fix_property_images.php                          fill gaps only
 |   php scripts/fix_property_images.php --dry-run                preview, change nothing
 |   php scripts/fix_property_images.php --regen                  re-render every image
 |   php scripts/fix_property_images.php --property=SN-2026-001   one property (ID or code)
 |   php scripts/fix_property_images.php --property=12 --regen
 |   php scripts/fix_property_images.php --limit=5                process first N properties
 |
 | On Railway:
 |   railway run php scripts/fix_property_images.php
 | or enable the self-healing hook: set environment variable
 |   WJ_RUN_IMAGE_FIX=1   (entrypoint runs this script on every boot, idempotent)
 |=============================================================================
 */

